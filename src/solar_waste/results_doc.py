STRUCTURAL = [
    r"\b\d{1,2} (January|February|March|April|May|June|July|August|September|October|November|December) \d{4}\b",
    r"\d{4}-\d{2}-\d{2}",                 # dates
    r"\b\d{4}-\d{2}\b",                   # year-month
    r"\b(19|20)\d{2}\b",                  # years
    r"\b85\d{4}\b", r"\b854\d{3}\b",      # HS codes
    r"§\s?\d+(\.\d+)*", r"\bpp?\.\s?\d+(-\d+)?(, \d+)*",  # section and page references
    r"S\.I\. No\. \d+", r"Regs?\. [\dA-Za-z(), ]+?(?=[ .:;,)]|$)", r"Schedules? \d+(-\d+)?",
    r"Table \d+(-\d+)?", r"Figure \d+(-\d+)?", r"HS\s?\d{4}", r"^\s*\d+\.\s", r"\bitems \d+ and \d+", r"\bitem \d+",
    r"\b\d+(st|nd|rd|th)\b", r"\bk = ", r"SHA-256",
    r"^#+\s*\d+\.", r"CC BY 4\.0", r"\d{4}-\d{2}\b", r"\(\d+\)(-\(\d+\))?", r"\([a-z]\)",
    r"\b\d{1,2} (January|February|March|April|May|June|July|August|September|October|November|December) \d{4}\b",
]


def check() -> list[dict]:
    text = OUT.read_text(encoding="utf-8")
    traced = {r["text"] for r in csv.DictReader(open(I / "results_number_trace.csv", encoding="utf-8"))}
    out = []
    for n, line in enumerate(text.splitlines(), 1):
        stripped = line
        for pat in STRUCTURAL:
            stripped = re.sub(pat, " ", stripped, flags=re.M)
        stripped = re.sub(r"`[^`]*`", " ", stripped)  # file names, hashes, code
        stripped = re.sub(r"https?://\S+", " ", stripped)
        for m in re.finditer(r"(?<![\w.])\d[\d,]*(\.\d+)?(?![\w])", stripped):
            tok = m.group(0).rstrip(",")
            if tok not in traced:
                out.append(dict(line=n, token=tok, context=line.strip()[:160]))
    with open(I / "results_untraced_numbers.csv", "w", newline="", encoding="utf-8") as f:
        wr = csv.DictWriter(f, fieldnames=["line", "token", "context"], lineterminator="\n")
        wr.writeheader()
        wr.writerows(out)
    return out


