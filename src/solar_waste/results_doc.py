"""Phase 4: generate docs/results.md from the output files (no typed numbers).

Every number inserted is produced by V(), which records the formatted string and its source file
(and derivation) in data/interim/results_number_trace.csv. check() then scans results.md for numeric
tokens and lists any that are not traceable (structural numbers such as years, HS codes, regulation and
section references, list markers and dates are excluded by fixed patterns).
"""
from __future__ import annotations

import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
P, I, D = ROOT / "data" / "processed", ROOT / "data" / "interim", ROOT / "docs"
OUT = D / "results.md"
TRACE: list[dict] = []


def V(value, fmt: str, source: str) -> str:
    s = format(value, fmt)
    TRACE.append(dict(text=s, value=value, source=source))
    return s


def rows(name, folder=P):
    with open(folder / name, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def t(x):  # thousands of tonnes, no decimals
    return ",.0f"


def main() -> None:
    TRACE.clear()
    params = json.loads((P / "parameters.json").read_text(encoding="utf-8"))
    ann = {s: {(r["product"], r["year"]): r for r in rows(f"rq2_waste_annual{s}.csv")} for s in ("", "_s10")}
    cum = {s: {r["product"]: r for r in rows(f"rq2_waste_cumulative{s}.csv")} for s in ("", "_s10")}
    lbl = {"": "(a) locked-in", "_s10": "(b) continuing imports at the 2025 level"}
    fsrc = {"": "rq2_waste_annual.csv", "_s10": "rq2_waste_annual_s10.csv"}
    csrc = {"": "rq2_waste_cumulative.csv", "_s10": "rq2_waste_cumulative_s10.csv"}
    prods = [("batteries_850720_850760", "Batteries (lead-acid 850720 + lithium-ion 850760)"),
             ("850720", "Lead-acid 850720"), ("850760", "Lithium-ion 850760"),
             ("850440", "Inverters / static converters 850440"),
             ("panels_regular", "PV panels, regular-loss"), ("panels_early", "PV panels, early-loss")]

    def cell(r, src, col="median_t"):
        m = V(float(r[col]), ",.0f", src)
        lo, hi = float(r["p05_t"]), float(r["p95_t"])
        if abs(hi - lo) >= 0.5:
            return f"{m} [{V(lo, ',.0f', src)}-{V(hi, ',.0f', src)}]"
        return m

    L = []
    w = L.append
    w("# Results")
    w("")
    w("*The solar boom's hidden bill: Nigeria's coming wave of solar panel and battery waste*")
    w("")
    w("This document is generated by `src/solar_waste/results_doc.py` from the output files in `data/processed/`. "
      "Each number is traced to its file in `data/interim/results_number_trace.csv`. "
      "Plan: `docs/analysis_plan.md` (Amendments A1-A7). Frozen parameters: `data/processed/parameters.json`, SHA-256 recorded in plan §10.2.")
    w("")
    w("> Trade-derived values: **Source: UN Comtrade.** Licence: https://comtrade.un.org/licenseagreement.html. "
      "Ember China Solar PV Exports and World Bank commodity prices: CC BY 4.0.")
    w("")
    w("**How to read the numbers:**")
    w("")
    w("- Tonnes are imported mass (net weight).")
    w("- Results cover full HS trade volumes. They are not solar-only.")
    w("- Uncertain values are given as the median, with the 5th-95th percentile in brackets where it differs.")
    w("")

    # 1. Waste, two series
    w("## 1. Waste from imported solar and backup-power equipment (RQ2)")
    w("")
    w("Two series are reported side by side (Amendment A5):")
    w("")
    w("- **(a) Locked-in waste:** equipment imported to date. This is the main result and a lower bound.")
    w("- **(b) Continuing imports at the 2025 level:** sensitivity S10. This is a scenario, not a forecast.")
    w("")
    w("| Product | Series | 2025 | 2030 | 2035 | 2040 | Cumulative 2013-2040 |")
    w("|---|---|---|---|---|---|---|")
    for key, name in prods:
        for s in ("", "_s10"):
            cells = [cell(ann[s][(key, y)], fsrc[s]) for y in ("2025", "2030", "2035", "2040")]
            w(f"| {name if s == '' else ''} | {lbl[s]} | " + " | ".join(cells) + f" | {cell(cum[s][key], csrc[s])} |")
    w("")
    w("*Why (a) declines:* series (a) includes only equipment imported to date, so annual waste falls once those cohorts have retired. "
      "Series (b) adds imports held at the 2025 level for 2026-2040. Figure: `figures/phase2_waste_by_product.png`.")
    w("")
    st = cum[""]
    w(f"In series (a), these quantities are still in use at the end of 2040: "
      f"{V(float(st['850760']['stock_end_2040_median_t']), ',.0f', 'rq2_waste_cumulative.csv')} t of lithium-ion batteries, and "
      f"{V(float(st['panels_regular']['stock_end_2040_median_t']), ',.0f', 'rq2_waste_cumulative.csv')} t (regular-loss) or "
      f"{V(float(st['panels_early']['stock_end_2040_median_t']), ',.0f', 'rq2_waste_cumulative.csv')} t (early-loss) of panels.")
    w("")

    # 2. Chemistry
    bc = {int(r["year"]): r for r in rows("rq1_battery_chemistry.csv")}
    fm = min(y for y, r in bc.items() if float(r["lithiumion_850760_t"]) > float(r["leadacid_850720_t"]))
    fu = min(y for y, r in bc.items() if float(r["lithiumion_850760_musd"]) > float(r["leadacid_850720_musd"]))
    src = "rq1_battery_chemistry.csv"
    w("## 2. Battery chemistry in imports (RQ1)")
    w("")
    w(f"Partner-reported imports of lithium-ion batteries (850760) first exceeded lead-acid batteries (850720) by mass in {V(fm, 'd', 'derived: rq1_battery_chemistry.csv (first year Li-ion t > lead-acid t)')} "
      f"({V(float(bc[fm]['lithiumion_850760_t']), ',.0f', src)} t vs {V(float(bc[fm]['leadacid_850720_t']), ',.0f', src)} t). "
      f"By value they first exceeded them in {V(fu, 'd', 'derived: rq1_battery_chemistry.csv (first year Li-ion USD > lead-acid USD)')} (USD {V(float(bc[fu]['lithiumion_850760_musd']), '.1f', src)} m vs "
      f"{V(float(bc[fu]['leadacid_850720_musd']), '.1f', src)} m). "
      f"In 2025 the lithium-ion to lead-acid ratio was {V(float(bc[2025]['ratio_liion_to_leadacid_t']), '.2f', src)} by mass and "
      f"{V(float(bc[2025]['ratio_liion_to_leadacid_usd']), '.2f', src)} by value. Both codes cover all uses, not only solar.")
    w("")
    w("| Year | Lead-acid 850720, t | Lithium-ion 850760, t |")
    w("|---|---|---|")
    for y in (2012, 2016, 2020, 2022, 2024, 2025):
        w(f"| {y} | {V(float(bc[y]['leadacid_850720_t']), ',.0f', src)} | {V(float(bc[y]['lithiumion_850760_t']), ',.0f', src)} |")
    w("")
    imp = {r["product"] + r["year"]: r for r in rows("rq1_imports.csv")}
    w(f"Panel imports (main series) were {V(float(imp['panels2017']['main_t']), ',.0f', 'rq1_imports.csv')} t "
      f"({V(float(imp['panels2017']['main_mw']), ',.1f', 'rq1_imports.csv')} MW) in 2017 and "
      f"{V(float(imp['panels2025']['main_t']), ',.0f', 'rq1_imports.csv')} t "
      f"({V(float(imp['panels2025']['main_mw']), ',.1f', 'rq1_imports.csv')} MW) in 2025. "
      f"January-September 2026 reached {V(float(imp['panels2026']['main_t']), ',.0f', 'rq1_imports.csv')} t "
      f"({V(float(imp['panels2026']['main_mw']), ',.1f', 'rq1_imports.csv')} MW; partial year). "
      "Figure: `figures/phase2_imports_by_product.png`.")
    w("")
    ig = {r["product"]: r for r in rows("import_growth_2021_2025.csv")}
    gsrc = "import_growth_2021_2025.csv"
    w(f"From 2021 to 2025, partner-reported panel imports rose from {V(float(ig['panels']['mass_2021_t']), ',.0f', gsrc)} t to "
      f"{V(float(ig['panels']['mass_2025_t']), ',.0f', gsrc)} t ({V(float(ig['panels']['ratio_2025_to_2021']), '.1f', gsrc)} times). "
      f"Lithium-ion imports rose from {V(float(ig['850760']['mass_2021_t']), ',.0f', gsrc)} t to "
      f"{V(float(ig['850760']['mass_2025_t']), ',.0f', gsrc)} t ({V(float(ig['850760']['ratio_2025_to_2021']), '.1f', gsrc)} times) "
      "(`data/processed/import_growth_2021_2025.csv`).")
    w("")

    # 3. Lead-acid gap
    g = {(r["series"], r["product"], r["year"]): r for r in rows("rq4_gap_leadacid.csv")}
    cap = float(params["recycling_capacity"]["ulab_input_t_per_year"])
    s25 = g[("locked_in", "850720_plus_850710", "2025")]
    a25, b25 = g[("locked_in", "850720", "2025")], g[("locked_in", "850710", "2025")]
    src = "rq4_gap_leadacid.csv"
    w("## 3. Lead-acid batteries: waste against recycling capacity (RQ4)")
    w("")
    w(f"In 2025, lead-acid battery waste was {cell({'median_t': a25['waste_median_t'], 'p05_t': a25['waste_p05_t'], 'p95_t': a25['waste_p95_t']}, src)} t from 850720 "
      f"and {V(float(b25['waste_median_t']), ',.0f', src)} t from starter batteries (850710). The sum was "
      f"{cell({'median_t': s25['waste_median_t'], 'p05_t': s25['waste_p05_t'], 'p95_t': s25['waste_p95_t']}, src)} t. "
      f"This is set against the documented nameplate capacity of {V(cap, ',.0f', 'parameters.json (GIZ 2025 Table 2-1 p.11)')} t/a of used-battery input "
      f"(GIZ 2025). Capacity exceeds the trade-based waste by {V(float(s25['capacity_minus_waste_median_t']), ',.0f', src)} t; the waste equals "
      f"{V(100 * float(s25['waste_median_t']) / cap, '.1f', 'derived: rq4_gap_leadacid.csv / parameters.json')}% of capacity. "
      "Capacity is nameplate, not throughput. No plant-level throughput figure was found.")
    w("")
    g40a, g40b = g[("locked_in", "850720_plus_850710", "2040")], g[("continuing_2025_level_S10", "850720_plus_850710", "2040")]
    w(f"In 2040 the sum is {V(float(g40a['waste_median_t']), ',.0f', src)} t in series (a) and "
      f"{V(float(g40b['waste_median_t']), ',.0f', src)} t in series (b). *Why (a) declines:* it includes no imports after 2025.")
    w("")
    w("**Documented explanations** for capacity exceeding the trade-based waste, as the sources state them; none is selected (`docs/phase3_results.md` §2.1):")
    w("")
    w("1. Plants operate below nameplate capacity (GIZ 2025 pp.10, 34; BusinessDay 2017, 2018).")
    w("2. Some batteries are outside the trade series:")
    w("   - batteries manufactured in Nigeria (GIZ 2025 p.11; IDS 2016);")
    w("   - generation estimated from the vehicle fleet (Ogundele et al. 2020).")
    w("3. Used batteries flow in from neighbouring countries, reported as illegal (IDS 2016; Lead Battery Notes 2025; GIZ 2025 p.21).")
    w("4. Nigeria-reported and partner-reported trade records differ (§7).")
    w("5. Independent generation estimates are higher than the trade-based figures (GIZ 2025 p.9; EnviroNews 2017; BusinessDay 2018).")
    w("6. Used batteries are exported (BusinessDay 2017).")
    w("")
    inf = {(r["series"], r["base"], r["informal_share"], r["quantity"]): r for r in rows("rq5_informal_scenarios.csv")}
    w("**Illustrative scenarios, not estimates.** If a stated share of 2025 lead-acid waste (850720 + 850710) went through informal recovery, "
      "the lead passing through it would be:")
    w("")
    for sh in ("0.25", "0.5", "0.75"):
        r = inf[("locked_in", "850720_plus_850710", sh, "lead_through_informal_t")]
        w(f"- {V(100 * float(sh), '.0f', 'rq5_informal_scenarios.csv (share)')}% share: {V(float(r['y2025_median_t']), ',.0f', 'rq5_informal_scenarios.csv')} t of lead.")
    w("")

    # 4. No documented capacity
    o = {(r["series"], r["product"], r["year"]): r for r in rows("rq4_gap_other.csv")}
    src = "rq4_gap_other.csv"
    w("## 4. Lithium-ion batteries, panels and inverters: no documented recycling capacity (RQ4)")
    w("")
    w("No recycling capacity for these streams in Nigeria was documented (Phase 0; Phase 1b search). The whole annual arising is therefore set against "
      "\"no documented capacity\", which is not the same as zero capacity.")
    w("")
    w("| Product | (a) 2030 | (a) 2040 | (b) 2030 | (b) 2040 |")
    w("|---|---|---|---|---|")
    for p, name in (("850760", "Lithium-ion 850760"), ("panels_regular", "Panels, regular-loss"), ("panels_early", "Panels, early-loss"), ("850440", "Inverters 850440")):
        vals = [V(float(o[(s, p, y)]["arising_median_t"]), ",.0f", src) for s in ("locked_in", "continuing_2025_level_S10") for y in ("2030", "2040")]
        w(f"| {name} | " + " | ".join(vals) + " |")
    w("")
    w("*Why (a) declines:* as in §1. Figure: `figures/phase3_recycling_gap.png`.")
    w("")

    # 5. Material value
    mc = {(r["series"], r["panel_scenario"], r["quantity"], r["stream"]): r for r in rows("rq5_materials_cumulative.csv")}
    src = "rq5_materials_cumulative.csv"
    w("## 5. Material mass and value (RQ5)")
    w("")
    w(f"Contained metal value, cumulative 2013-2040, is given in million USD, nominal, at the frozen mean World Bank prices for {params['prices']['lead']['main_window']}. It is gross and not net of costs. "
      "Inverters carry no material value; lithium-ion value covers copper and aluminium only (industry-commissioned LFP composition).")
    w("")
    w("| Series | Panels regular-loss | Panels early-loss |")
    w("|---|---|---|")
    for s, name in (("locked_in", "(a) locked-in"), ("continuing_2025_level_S10", "(b) continuing 2025 level")):
        vals = [V(float(mc[(s, ps, "contained_value_usd", "total_main_series")]["median"]) / 1e6, ",.1f", src) for ps in ("regular", "early")]
        w(f"| {name} | " + " | ".join(vals) + " |")
    w("")
    lead_a = mc[("locked_in", "regular", "mass_t", "lead_850720")]
    rec90 = mc[("locked_in", "regular", "recoverable_mass_t", "lead_850720_recoverable_formal90")]
    rec50 = mc[("locked_in", "regular", "recoverable_mass_t", "lead_850720_recoverable_informal50")]
    rec60 = mc[("locked_in", "regular", "recoverable_mass_t", "lead_850720_recoverable_informal60")]
    w(f"In series (a), lead contained in lead-acid waste (850720) totals {V(float(lead_a['median']), ',.0f', src)} t. Recovery would yield "
      f"{V(float(rec90['median']), ',.0f', src)} t at the formal rate and {V(float(rec50['median']), ',.0f', src)}-"
      f"{V(float(rec60['median']), ',.0f', src)} t at the informal rates (GIZ 2025 p.11). Figure: `figures/phase3_material_value.png`.")
    w("")

    # 6. C2-C1
    r3 = {(r["scenario"], r["panel_scenario"]): r for r in rows("rq3_scenarios.csv")}
    c1, c2 = "C1 imports to 2021 only", "C2 full series (main)"
    src = "derived: rq3_scenarios.csv (C2 - C1 medians)"
    w("## 6. Effect of the import period, and the Project Volt headline (RQ3)")
    w("")
    pb = {ps: float(r3[(c2, ps)]["panels_batteries_median_t"]) - float(r3[(c1, ps)]["panels_batteries_median_t"]) for ps in ("regular", "early")}
    a4 = {ps: float(r3[(c2, ps)]["total_median_t"]) - float(r3[(c1, ps)]["total_median_t"]) for ps in ("regular", "early")}
    w(f"Cumulative waste 2021-2040 from imports made in 2022-2026 (C2 − C1) is {V(pb['regular'], ',.0f', src)} t (regular-loss panels) and "
      f"{V(pb['early'], ',.0f', src)} t (early-loss) for panels and batteries (850720, 850760). With inverters (850440) included it is "
      f"{V(a4['regular'], ',.0f', src)} t and {V(a4['early'], ',.0f', src)} t.")
    w("")
    w(f"**Secondary comparison, not like for like.** The publicly reported Project Volt headline is about "
      f"{V(float(r3[(c1, 'regular')]['project_volt_headline_t']), ',.0f', 'rq3_scenarios.csv')} t of cumulative solar e-waste by 2040 (report p.12; CJID 2022). "
      f"The study's panels-and-batteries total is {V(float(r3[(c1, 'regular')]['panels_batteries_ratio_to_headline']), '.2f', 'rq3_scenarios.csv')}-"
      f"{V(float(r3[(c1, 'early')]['panels_batteries_ratio_to_headline']), '.2f', 'rq3_scenarios.csv')} times the headline for C1, and "
      f"{V(float(r3[(c2, 'regular')]['panels_batteries_ratio_to_headline']), '.2f', 'rq3_scenarios.csv')}-"
      f"{V(float(r3[(c2, 'early')]['panels_batteries_ratio_to_headline']), '.2f', 'rq3_scenarios.csv')} times for C2. "
      "The study uses full trade volumes from national trade records, while Project Volt counts solar components in an installed base. "
      "Differences are not attributed to Project Volt's assumptions.")
    w("")

    # 7. Mirror gap (approved wording, numbers from file)
    gg = rows("rq1_gap_usd_kg.csv")
    src = "derived: rq1_gap_usd_kg.csv (totals over years available)"

    def tot(prod):
        rs = [r for r in gg if r["product"] == prod]
        nu, pu = sum(float(r["nigeria_cif_usd"]) for r in rs), sum(float(r["partner_fob_usd"]) for r in rs)
        nt, pt = sum(float(r["nigeria_t"]) for r in rs), sum(float(r["partner_t"]) for r in rs)
        return 100 * (pu - nu) / pu, 100 * (pt - nt) / pt, nt / pt
    la, li, st_, inv = tot("850720"), tot("850760"), tot("850710"), tot("850440")
    oa = {(r["hs"], r["year"]): r for r in rows("rq1_other_accumulators.csv")}
    osrc = "rq1_other_accumulators.csv"
    w("## 7. Nigeria-reported and partner-reported imports (RQ1)")
    w("")
    w("This section uses the wording verified in `docs/phase2_mirror_check.md` §4 (Amendment A6), with numbers recomputed from `data/processed/rq1_gap_usd_kg.csv`.")
    w("")
    w(f"> Imports were taken from partner-reported trade (all reporters' exports to Nigeria; Source: UN Comtrade). Nigeria's own reported imports, which UN Comtrade "
      f"holds for every year 2012-2025, differ from partner-reported values. Over 2012-2025 they are {V(la[0], '.0f', src)}% lower in value and {V(la[1], '.0f', src)}% lower "
      f"in mass for lead-acid batteries (HS 850720), {V(li[0], '.0f', src)}% lower in value and {V(li[1], '.0f', src)}% lower in mass for lithium-ion batteries "
      f"(HS 850760, 2015-2025), and {V(st_[0], '.0f', src)}% lower in value and {V(st_[1], '.0f', src)}% lower in mass for starter batteries (HS 850710). "
      f"For static converters (HS 850440), Nigeria-reported values are {V(inv[0], '.0f', src)}% lower than partner-reported values, while Nigeria-reported mass is "
      f"{V(inv[2], '.1f', src)} times partner-reported mass. Nigeria's reported net weight for this code is flagged by UN Comtrade as estimated in every year from 2014. "
      "These differences are reported, not corrected. UN Comtrade lists differences in partner attribution, CIF and FOB valuation, timing, transit through third "
      "countries and classification among the general causes of such asymmetries.")
    w("")
    w(f"> Before 2015, Nigeria reported in HS2007, which has no separate code for lithium-ion accumulators (850760). Nigeria-reported imports of \"other accumulators\" "
      f"(HS 850780) were USD {V(float(oa[('850780', '2012')]['NGA_imports_world_usd']) / 1e6, '.1f', osrc)} m in 2012 and "
      f"USD {V(float(oa[('850780', '2013')]['NGA_imports_world_usd']) / 1e6, '.1f', osrc)} m in 2013, against "
      f"USD {V(float(oa[('850780', '2012')]['ALL_exports_to_NGA_usd']) / 1e6, '.1f', osrc)} m and "
      f"{V(float(oa[('850780', '2013')]['ALL_exports_to_NGA_usd']) / 1e6, '.1f', osrc)} m reported by partners. These are not included in the study's series.")
    w("")

    # 8. RQ6
    r6 = rows("rq6_regulation_review.csv")
    from collections import Counter
    cc = Counter(r["evidence_code"] for r in r6)
    src = "rq6_regulation_review.csv"
    w("## 8. Regulation and public reporting on implementation (RQ6)")
    w("")
    w(f"{V(len(r6), 'd', src)} duties were reviewed, from S.I. No. 11 of 2024 and, for PV panels, S.I. No. 79 of 2022. "
      f"{V(cc['public record of implementation found'], 'd', src)} have a public record of implementation, "
      f"{V(cc['public statement of intent only'], 'd', src)} a public statement of intent only, "
      f"{V(cc['public record indicates not implemented'], 'd', src)} a public record indicating that they are not implemented, and "
      f"{V(cc['no public record found'], 'd', src)} no public record found. "
      f"For {V(sum(r['enforcement_action'] == 'yes' for r in r6), 'd', src)} duties a documented enforcement action was found. "
      "\"Public record indicates not implemented\" is used only where a source states non-implementation explicitly (Amendment A7). "
      "\"No public record found\" is not evidence of non-compliance.")
    w("")
    for did in ("D03", "D10", "D11", "D14", "D17"):
        r = next(x for x in r6 if x["duty_id"] == did)
        enf = f" Enforcement action: {r['enforcement_action']}" + (f" ({r['enforcement_source']})." if r["enforcement_source"] else ".")
        w(f"- **{r['provision']}:** {r['duty']}. Code: *{r['evidence_code']}*." + (f" Source: {r['evidence_source']}, {r['evidence_date']}." if r["evidence_date"] else "") + enf)
    w("")
    w("Details: `docs/phase4_results.md`.")
    w("")

    # 9. Limitations and cannot-claim (from plan §9)
    plan = (D / "analysis_plan.md").read_text(encoding="utf-8")
    sec9 = plan[plan.index("## 9. What the study cannot claim"):plan.index("## 10.")]
    items = [ln for ln in sec9.splitlines() if re.match(r"^\d+\. ", ln)]
    w("## 9. Limitations and what the study cannot claim")
    w("")
    w("**Main limitations:**")
    w("")
    w(f"- **Uncertainty:** the Monte Carlo uses {V(params['monte_carlo']['draws'], ',d', 'parameters.json')} draws with a fixed seed. Only lead-acid and inverter lifetimes are sampled; other lifetimes are fixed values from published sources.")
    w(f"- **Battery and inverter lifetimes:** these use a Weibull shape k = {V(params['lifetimes']['batteries_inverters_distribution']['k'], '.1f', 'parameters.json')}, which has no source.")
    w("- **Panel lifetime formula:** the published IRENA form does not reproduce IRENA's stated supporting points. A calibrated alternative is a sensitivity (S23).")
    w("- **Sensitivities:** results are sensitive to the import source (Nigeria-reported vs partner-reported), to panel lifetime and to continuing imports (`docs/phase2_results.md` §3; `docs/phase3_results.md` §4).")
    w(f"- **Panel composition:** the IRENA composition shares sum to slightly more than one, because silver is given as less than {V(100 * params['composition']['panels_c_si']['silver_S12'][1], '.1f', 'parameters.json')}%. This is reported, not corrected.")
    w("")
    w("**What the study cannot claim** (plan §9, reproduced verbatim; section references in this list are to `docs/analysis_plan.md`):")
    w("")
    for ln in items:
        w(ln)
    w("")

    # 10. Amendments
    w("## 10. Amendment log (summary)")
    w("")
